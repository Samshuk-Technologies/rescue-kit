#!/usr/bin/env node
/**
 * Generate docs/rules.md from the ruleset itself.
 *
 * A hand-maintained rule reference drifts the moment someone tunes a severity, and a
 * security tool whose documentation disagrees with its behaviour is worse than one with
 * no documentation. CI regenerates this and fails if the committed copy differs.
 *
 *   node scripts/generate-rules-doc.mjs           # write docs/rules.md
 *   node scripts/generate-rules-doc.mjs --check   # exit 1 if it would change
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allRules } from '../dist/index.js';
import { CATEGORY_LABELS, SEVERITY_WEIGHT } from '../dist/index.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'docs', 'rules.md');

const CATEGORY_ORDER = ['secrets', 'auth', 'payments', 'data', 'testing', 'operations'];
const SEVERITY_ORDER = { critical: 0, high: 1, medium: 2, low: 3 };

const CATEGORY_INTROS = {
  secrets:
    'Credentials that have escaped, or are one build away from escaping. These are weighted most heavily because they are the least recoverable: a key that reached a browser bundle or a git history is already public.',
  auth:
    'Who the caller is, and what they are allowed to do. The most common source of exploitable bugs in prototype code, because auth is the part an app appears to work perfectly well without.',
  payments:
    'Taking money correctly. These rules only run when a payment provider is installed. Every one of them corresponds to a way prototypes lose real money — to fraud, to duplicate charges, or to orders that are paid for and never fulfilled.',
  data:
    'The database and what reaches it. Covers both security (injection, row-level security) and the schema decisions that are invisible on seed data and painful at scale.',
  testing:
    'Whether anything verifies a change before users do. Weighted lower than security categories — not because it matters less, but because it is recoverable: you can add tests next sprint with no lasting harm.',
  operations:
    'Running the thing once it is live. Error visibility, abuse resistance, reproducible builds.',
};

function esc(text) {
  return text.replace(/\|/g, '\\|');
}

function formatEffort(hours) {
  if (hours <= 2) return `${hours}h`;
  const days = Math.round((hours / 8) * 10) / 10;
  return `${hours}h (~${days}d)`;
}

const byCategory = new Map(CATEGORY_ORDER.map((c) => [c, []]));
for (const rule of allRules) byCategory.get(rule.category).push(rule);
for (const rules of byCategory.values()) {
  rules.sort(
    (a, b) => SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity] || a.id.localeCompare(b.id),
  );
}

const totalEffort = allRules.reduce((sum, r) => sum + r.effortHours, 0);
const counts = Object.fromEntries(
  Object.keys(SEVERITY_ORDER).map((s) => [s, allRules.filter((r) => r.severity === s).length]),
);

const lines = [];

lines.push('<!-- Generated by scripts/generate-rules-doc.mjs. Do not edit by hand. -->');
lines.push('');
lines.push('# Rule reference');
lines.push('');
lines.push(
  `All ${allRules.length} rules Rescue Kit applies, grouped by category and ordered by severity.`,
);
lines.push('');
lines.push(
  'This page is generated from the ruleset, so it always matches what the tool actually does.',
);
lines.push('');

// ── Summary ────────────────────────────────────────────────────────────────
lines.push('## At a glance');
lines.push('');
lines.push('| | Critical | High | Medium | Low | Total |');
lines.push('| --- | --- | --- | --- | --- | --- |');

for (const category of CATEGORY_ORDER) {
  const rules = byCategory.get(category);
  const n = (sev) => rules.filter((r) => r.severity === sev).length || '—';
  lines.push(
    `| **${CATEGORY_LABELS[category]}** | ${n('critical')} | ${n('high')} | ${n('medium')} | ${n('low')} | ${rules.length} |`,
  );
}
lines.push(
  `| **All** | ${counts.critical} | ${counts.high} | ${counts.medium} | ${counts.low} | **${allRules.length}** |`,
);
lines.push('');
lines.push(
  `A project failing every applicable rule would carry an estimated ${totalEffort} engineer-hours of remediation.`,
);
lines.push('');

// ── Severity meaning ───────────────────────────────────────────────────────
lines.push('## What the severities mean');
lines.push('');
lines.push('| Severity | Meaning | Score cost |');
lines.push('| --- | --- | --- |');
lines.push(
  `| **Critical** | Exploitable in production right now, or money/data already at risk | −${SEVERITY_WEIGHT.critical} to its category |`,
);
lines.push(
  `| **High** | No live exploit, but a serious gap that will cause incidents under real traffic | −${SEVERITY_WEIGHT.high} |`,
);
lines.push(
  `| **Medium** | Will cause avoidable pain — duplicate charges, unreproducible builds, slow queries | −${SEVERITY_WEIGHT.medium} |`,
);
lines.push(
  `| **Low** | Worth fixing, costs little, blocks nothing | −${SEVERITY_WEIGHT.low} |`,
);
lines.push('');
lines.push('See [the scoring model](./scoring.md) for how these combine into a grade.');
lines.push('');

// ── Rules ──────────────────────────────────────────────────────────────────
for (const category of CATEGORY_ORDER) {
  const rules = byCategory.get(category);
  if (rules.length === 0) continue;

  lines.push('---');
  lines.push('');
  lines.push(`## ${CATEGORY_LABELS[category]}`);
  lines.push('');
  lines.push(CATEGORY_INTROS[category]);
  lines.push('');

  for (const rule of rules) {
    lines.push(`### \`${rule.id}\``);
    lines.push('');
    lines.push(`**${esc(rule.title)}**`);
    lines.push('');
    lines.push(
      `| Severity | Effort | Runs when |`,
    );
    lines.push('| --- | --- | --- |');
    lines.push(
      `| ${rule.severity} | ${formatEffort(rule.effortHours)} | ${rule.appliesTo ? 'conditional — see below' : 'always'} |`,
    );
    lines.push('');
    lines.push(`**Fix:** ${esc(rule.remediation)}`);
    lines.push('');
  }
}

lines.push('---');
lines.push('');
lines.push('## Conditional rules');
lines.push('');
lines.push(
  'Rules marked *conditional* are skipped when they cannot apply — for example, payment rules on a project with no payment provider installed. A skipped rule does not count as a pass: **its whole category is excluded from the score** rather than credited. Crediting a project for security it does not implement would inflate every score and make comparison meaningless.',
);
lines.push('');
lines.push(
  'Run with `--json` to see `rulesRun` and `rulesSkipped` for a given project.',
);
lines.push('');
lines.push('## Proposing a rule');
lines.push('');
lines.push(
  'Rules are small — a data object, a `run` function, and two tests. See [CONTRIBUTING.md](../CONTRIBUTING.md).',
);
lines.push('');

const output = `${lines.join('\n')}`;

if (process.argv.includes('--check')) {
  let existing = '';
  try {
    existing = readFileSync(target, 'utf8');
  } catch {
    console.error('docs/rules.md is missing. Run: npm run docs:rules');
    process.exit(1);
  }
  if (existing !== output) {
    console.error('docs/rules.md is out of date. Run: npm run docs:rules');
    process.exit(1);
  }
  console.log(`docs/rules.md is up to date (${allRules.length} rules).`);
} else {
  writeFileSync(target, output);
  console.log(`Wrote docs/rules.md — ${allRules.length} rules.`);
}
